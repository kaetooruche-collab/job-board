HERE = os.path.dirname(os.path.abspath(__file__))
SITE = "https://yirehcareers.vercel.app"
MAIL = "yirehcareers@gmail.com"

NAME = "Yireh Careers"
CATEGORY = "Professional Services"
ABOUT = "Verified remote jobs, plus CVs, cover letters and LinkedIn profiles written for you. Free quick CV check. Message us to start."
DESCRIPTION = (
    "Yireh Careers lists verified remote jobs, each linked to the employer's own posting and refreshed every 6 hours. "
    "We also write CVs, cover letters and LinkedIn profiles (from $29), and we offer a free quick CV check to get you started. "
    f"Send documents by email ({MAIL}) and use WhatsApp for questions. We never charge job seekers to apply."
)
WEB1 = f"{SITE}/?utm_source=whatsapp&utm_medium=profile&utm_campaign=profile"
WEB2 = f"{SITE}/services?utm_source=whatsapp&utm_medium=profile&utm_campaign=profile"

CATALOG = [
    ("Essential: professionally written CV", "$29", "A polished, ATS-optimised CV written around your target roles, in Word and PDF. Up to 2 revision rounds. Delivered within 2 working days of completing onboarding."),
    ("Professional: CV, cover letter and LinkedIn setup (Recommended)", "$49", "Everything in Essential, plus a targeted cover letter and LinkedIn profile setup. Up to 3 revision rounds. Delivered within 3 working days of completing onboarding."),
    ("Executive: Professional plus 30-day LinkedIn service", "$149", "Everything in Professional, plus a personal branding strategy, 12 LinkedIn posts over 30 days and targeted connection building by hand each week, aiming towards 500+ total connections (or 100 new relevant ones if you already have 500+). We do not promise interviews or job offers."),
    ("LinkedIn Growth (monthly, optional after Executive)", "$99 per month", "12 curated posts and weekly targeted connection requests, month to month. Paid by arrangement here on WhatsApp. Nothing is charged automatically."),
    ("Free quick CV check", "Free", "Email your CV and we tell you the three things we would fix first. One free check per person."),
]

LABELS = ["New enquiry", "Free CV check", "Awaiting payment", "Paid", "Onboarding", "In progress", "Delivered", "Complete", "Privacy request"]

CHANNEL_NAME = "Yireh Careers Jobs"
CHANNEL_DESC = "Verified remote jobs, each linked to the employer's own posting and refreshed every 6 hours. Please check each employer's eligibility rules before you apply."

SOURCES = [
    ("TikTok bio", "TikTok"), ("Facebook page", "Facebook"), ("Snapchat profile", "Snapchat"),
    ("Instagram bio", "Instagram"), ("A WhatsApp group post", "a WhatsApp group"), ("The website", "the website"),
]

BANNED = ["guarantee", "no work permit", "only job board", "perfect for", "ideal for graduates"]


def wa(src):
    msg = f"Hello, I found Yireh Careers on {src}. I would like a free quick CV check."
    return "https://wa.me/905338225854?text=" + urllib.parse.quote(msg)


def block(text):
    return "```\n" + text.strip() + "\n```\n"


def library():
    t = open(os.path.join(HERE, "whatsapp-messages.md"), encoding="utf-8").read()
    out = []
    for s in re.split(r"\n(?=#{2,3} \d+[a-z]?\. )", t)[1:]:
        head = s.split("\n", 1)[0].lstrip("# ").strip()
        m = re.search(r"Shortcut `([^`]+)`", s)
        quote = "\n".join(re.sub(r"^> ?", "", l) for l in s.splitlines() if l.startswith(">"))
        if m and quote.strip():
            extra = ""
            inc = re.search(r"Inclusions to paste:\n((?:- .*\n?)+)", s)
            if inc:
                extra = inc.group(1)
            out.append((head, m.group(1), quote, extra))
    return out


def main():
    for label, text in [("about", ABOUT), ("description", DESCRIPTION), ("channel", CHANNEL_DESC)]:
        low = text.lower()
        assert not any(b in low for b in BANNED), (label, text)
    assert len(ABOUT) <= 139, len(ABOUT)
    assert len(DESCRIPTION) <= 512, len(DESCRIPTION)

    o = []
    o.append("# WhatsApp Business setup kit: Yireh Careers\n")
    o.append("Generated by `drafts/build_whatsapp_setup.py` from `drafts/whatsapp-messages.md`. Do not edit this file by hand.\n")
    o.append("Everything below is ready to copy. In the Claude app, tap the copy icon on each grey box, then paste it into the WhatsApp Business app on the phone for +90 533 822 5854. Screen names can change between app versions; the order below follows the app's menus (Settings, then Business tools). WhatsApp shows a character counter in each field; the limits I used are the lower, safer ones (I could not confirm the app's current limits from official documentation).\n")

    o.append("## Do these in order (about 30 minutes)\n")
    for i, step in enumerate([
        "Profile picture (section 1)", "Business name and category (section 2)", "About and description, email, website links (section 3)",
        "Greeting and away message (section 4)", "Quick replies (section 5): add the ones you need first, the rest later",
        "Labels (section 6)", "Catalog (section 7)", "Channel (section 8)", "Links for your bios (section 9)", "Test everything from a different phone (section 10)"], 1):
        o.append(f"{i}. {step}")
    o.append("")

    o.append("## 1. Profile picture\n")
    o.append("Three pictures are saved next to this file in `drafts/whatsapp-profile/` (PNG for the app, SVG for printing or editing). All keep everything inside the circle WhatsApp crops to. `preview-circles.png` shows how each looks at the sizes people will see.\n")
    o.append("- `yc-mark.png`: **recommended.** A white Y whose right arm is a light-blue tick, on a blue tile over navy. No words, so it stays clear in the small circle beside your business name (WhatsApp shows \"Yireh Careers\" next to the picture anyway). It matches the site's navy and blue.")
    o.append("- `yc-monogram.png`: the letters YC. A good second choice if you want the initials visible.")
    o.append("- `yc-mark-with-name.png`: the mark with the name under it. The words are too small to read in a chat circle, so use it for bigger places (a Facebook cover, a flyer), not WhatsApp.")
    o.append("\nIn the app: Settings, tap your profile picture, Edit, choose the file. The same picture works for the channel (section 8) and for TikTok, Facebook and Snapchat. A plain tick on its own is avoided on purpose: it looks like WhatsApp's own read ticks and verification badge.\n")

    o.append("## 2. Business name and category\n")
    o.append("Business name:\n")
    o.append(block(NAME))
    o.append("WhatsApp may need to approve a display-name change; it can take a few days. Category:\n")
    o.append(block(CATEGORY))

    o.append("## 3. Profile details (Settings, Business tools, Profile)\n")
    o.append(f"About (short line under your name, {len(ABOUT)} of 139 characters):\n")
    o.append(block(ABOUT))
    o.append(f"Business description ({len(DESCRIPTION)} of 512 characters):\n")
    o.append(block(DESCRIPTION))
    o.append("Email:\n")
    o.append(block(MAIL))
    o.append("Website 1 (the job board; the tags show in GoatCounter how many people came from your profile):\n")
    o.append(block(WEB1))
    o.append("Website 2 (the services page):\n")
    o.append(block(WEB2))
    o.append("Address: leave it empty unless you want a street address public on WhatsApp. If you do, use:\n")
    o.append(block("Yenice Sokak, 99300 Kyrenia, Cyprus"))
    o.append("Hours: set the hours you can really reply in (for example Monday to Friday). Do not promise instant replies. Your decision.\n")

    o.append("## 4. Greeting and away message (Settings, Business tools)\n")
    lib = library()
    byshort = {sc: (h, q, x) for h, sc, q, x in lib}
    # greeting and away have no shortcut; read them directly
    t = open(os.path.join(HERE, "whatsapp-messages.md"), encoding="utf-8").read()
    def grab(title):
        m = re.search(r"## " + re.escape(title) + r".*?\n((?:>.*\n?)+)", t)
        return "\n".join(re.sub(r"^> ?", "", l) for l in m.group(1).splitlines())
    greeting = grab("2. Greeting")
    away = grab("3. Away message").replace("[services page link]", f"{SITE}/services")
    o.append("Greeting message (turn on, send to new contacts and people who have not written for 14 days):\n")
    o.append(block(greeting))
    o.append("Away message (turn on, send outside your hours or always, your choice):\n")
    o.append(block(away))

    o.append("## 5. Quick replies (Settings, Business tools, Quick replies)\n")
    o.append("In each box the first line is the shortcut to type (the app adds the slash), then the message. Replace anything in [square brackets] when you use it. Never put bank or crypto details in the app until you have checked them twice; paste your own details where the brackets are.\n")
    for head, sc, q, extra in lib:
        o.append(f"### {head}\n")
        o.append(f"Shortcut: `{sc}`\n")
        o.append(block(q))
        if extra:
            o.append("Inclusions to paste into the brackets above:\n")
            o.append(block(extra))

    o.append("## 6. Labels (Settings, Business tools, Labels)\n")
    o.append("Create these in this order, then label each chat as it moves along. They are how you see at a glance who needs what.\n")
    o.append(block("\n".join(LABELS)))

    o.append("## 7. Catalog (Settings, Business tools, Catalog)\n")
    o.append("Add one item for each entry. Title, price, then description. Currency: USD. Add the photo if you like; the profile picture works.\n")
    for title, price, desc in CATALOG:
        o.append(f"**{title}**\n")
        o.append(block(f"Title: {title}\nPrice: {price}\nDescription: {desc}"))

    o.append("## 8. WhatsApp Channel (your existing jobs channel)\n")
    o.append("Open the channel, tap its name, Edit. Name:\n")
    o.append(block(CHANNEL_NAME))
    o.append("Description:\n")
    o.append(block(CHANNEL_DESC))
    o.append("Picture: the same profile picture. Weekly post: after the Tuesday email, paste the text from `data/whatsapp_post.txt` (Claude can show it to you; the same post can be built at `/kit` on the live site, WhatsApp tab) as the channel update.\n")

    o.append("## 9. Links for your bios (each one tags where the person came from)\n")
    o.append("A person who taps the link lands in a chat with you and the first message already says where they found you. Use one link per place so you can see which place works.\n")
    for label, src in SOURCES:
        o.append(f"{label}:\n")
        o.append(block(wa(src)))
    o.append(f"Job board link for the same bios (so people can browse first): {SITE}/?utm_source=<platform>&utm_medium=social&utm_campaign=bio (replace `<platform>` with tiktok, facebook, snapchat or instagram).\n")

    o.append("## 10. Test before you post (5 minutes)\n")
    o.append("1. From a different phone, open each bio link and check your phone receives the pre-filled message.")
    o.append("2. Send it a message from that phone and confirm the greeting arrives.")
    o.append("3. Type `/check` in a chat and confirm the free-CV-check quick reply appears, then open its form link on the phone and confirm the form loads.")
    o.append(f"4. Open {WEB1} on your phone and confirm the site opens.")
    o.append("5. Keep a note of what you changed and tell Claude anything that looks wrong.\n")

    o.append("## 11. Keep an enquiry log from day one\n")
    o.append("Use `drafts/enquiry-log-template.csv` (a spreadsheet with no names, only where the person found you, their country, whether they are a student, a recent graduate or working, what they asked for and what happened). It is the evidence the strategy review needs to decide who the customer is. Do not put names, emails or CV details in it.\n")

    path = os.path.join(HERE, "whatsapp-business-setup.md")
    open(path, "w", encoding="utf-8").write("\n".join(o) + "\n")
    print("wrote", path, "|", len(lib), "quick replies | about", len(ABOUT), "| description", len(DESCRIPTION))


if __name__ == "__main__":
    main()
