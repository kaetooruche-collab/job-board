"""Builds drafts/whatsapp-business-setup.md (copy-and-paste kit for the WhatsApp Business app)
from drafts/whatsapp-messages.md plus the profile text below.
Run: python3 drafts/build_whatsapp_setup.py
Edit the text here or in whatsapp-messages.md, then rebuild; do not edit the generated file by hand."""
