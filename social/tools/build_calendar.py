#!/usr/bin/env python3
"""Write social/calendar/<week>.md from <week>.posts.json, with each post's guardrail result.

    python3 social/tools/build_calendar.py social/calendar/2026-12-01.posts.json

The .posts.json file is the source (the checker and the renderer read it); the .md is for reading. Rendered files
and featured roles are listed when social/output/<date>/<id>/manifest.json exists.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_post  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
# Audience time zones (cities named only here, in a working file, to show local times; never in posts)
ZONES = [("Mexico City", "America/Mexico_City"), ("Toronto", "America/Toronto"), ("São Paulo", "America/Sao_Paulo"),
         ("London", "Europe/London"), ("Berlin", "Europe/Berlin"), ("Lagos", "Africa/Lagos"),
         ("Nairobi", "Africa/Nairobi"), ("Delhi", "Asia/Kolkata"), ("Manila", "Asia/Manila")]


def local_times(date: str, hhmm: str) -> str:
    t = dt.datetime.fromisoformat(f"{date}T{hhmm}:00+00:00")
    return " · ".join(f"{name} {t.astimezone(ZoneInfo(z)):%H:%M}" for name, z in ZONES)


def block(text: str) -> str:
    return "\n".join("> " + line if line else ">" for line in text.split("\n"))


def build(path: Path) -> Path:
    data = json.loads(path.read_text(encoding="utf-8"))
    out = [f"# {data['title']}", "",
           f"Status: **{data['status']}**  ",
           f"Numbers measured on the live board: {data['measured_on']} (every number is re-measured on the post day; the checker blocks scheduling until it is).  ",
           f"This week's test: {data['test']}  ",
           "Source of truth: `" + path.name + "` (this page is generated by `social/tools/build_calendar.py`).", "",
           "| Day | Time (UTC) | Post | Pillar | Format | Platforms | Guardrails |", "|---|---|---|---|---|---|---|"]
    rows, details = [], []
    hist = [q for other in sorted(path.parent.glob("*.posts.json")) if other != path for q in check_post.load_posts(other)]
    reps = check_post.check_repetition(hist + data["posts"])
    for p in data["posts"]:
        fs = check_post.check_post(p, "draft") + reps.get(p["id"], [])
        b = [f for f in fs if f.level == check_post.BLOCK]
        status = "FAIL" if b else ("pass, with notes" if fs else "pass")
        rows.append(f"| {p['day']} {dt.date.fromisoformat(p['date']):%d %b} | {p['time_utc']} | {p['title']} | {p['pillar']} | {p['format']} | {', '.join(p['platforms'])} | {status} |")
        d = [f"## {p['day']} {dt.date.fromisoformat(p['date']):%d %b}: {p['title']} (`{p['id']}`)", "",
             f"- **Time:** {p['time_utc']} UTC ({local_times(p['date'], p['time_utc'])})",
             f"- **Platforms:** {', '.join(p['platforms'])} · **Pillar:** {p['pillar']} · **Format:** {p['format']}",
             f"- **Hook:** {p['hook']}",
             f"- **Funnel:** {p.get('funnel', '?')} · **Judged by:** {p.get('goal_metric', '?')} · **Series:** {p.get('series', '-')}",
             f"- **Variable tested:** {p['variable']}",
             f"- **Visuals:** {p['visuals']}"]
        if p.get("production"):
            d.append(f"- **Production:** {p['production']}")
        if p.get("ai_label"):
            d.append("- **AI label:** ON (TikTok AI-generated content; Instagram/Facebook \"AI info\").")
        if p.get("needs_kt"):
            d.append(f"- **Needs KT:** {p['needs_kt']}")
        if p.get("script"):
            d += ["", "**Script (spoken):**", "", block(p["script"])]
        if p.get("on_screen"):
            d += ["", "**On screen:** " + " / ".join(f"“{s}”" for s in p["on_screen"])]
        r = p.get("render")
        if r:
            d += ["", "**Slides:**", ""]
            for i, s in enumerate(r["slides"], 1):
                if s["t"] == "jobs":
                    extra = ", open worldwide only" if s.get("worldwide_only") else ""
                    d.append(f"{i}. {s.get('count', 3)} role card(s) picked on the day from the live feed{extra}")
                elif s["t"] == "job":
                    d.append(f"{i}. Role card: `{s['id']}`")
                else:
                    txt = " — ".join(x for x in (s.get("kicker"), s.get("title"), s.get("sub") or s.get("body")) if x)
                    d.append(f"{i}. ({s['t']}) {txt}")
            man = ROOT / "social" / "output" / p["date"] / p["id"] / "manifest.json"
            if man.exists():
                m = json.loads(man.read_text(encoding="utf-8"))
                pngs = sorted(man.parent.glob("*.jpg"))
                d += ["", f"**Preview rendered {m['rendered_at']}** (re-rendered on the post day): " +
                      ", ".join(f"[`{x.name}`](../output/{p['date']}/{p['id']}/{x.name})" for x in pngs)]
                if m["jobs"]:
                    d += ["", "| Role in the preview | Company | Apply from | Posted | Pay | Posting open? |", "|---|---|---|---|---|---|"]
                    for j in m["jobs"]:
                        c = j.get("check") or {}
                        ok = f"yes ({c['checked_open_on']})" if c.get("ok") else ("NO: " + (c.get("contradiction") or c.get("closed_wording") or c.get("error") or "check") if c else "not checked")
                        d.append(f"| [{j['title']}]({j['sourceUrl']}) | {j['company']} | {j['apply_from']} | {j['postedAt'][:10]} | {j['salaryText'] or 'Not stated'} | {ok} |")
        d += ["", "**Caption:**", "", block(p["caption"]), "",
              "**Guardrail check (draft mode):** " + ("all clear" if not fs else ""), ""]
        d += [f"- {f}" for f in fs]
        details.append("\n".join(d))
    out += rows + ["", "Bio link (one per platform, so per-post clicks cannot be told apart): "
                   "`https://yirehcareers.vercel.app/?utm_source=<tiktok|instagram|facebook>&utm_campaign=bio`.", ""]
    out += ["\n\n".join(details), ""]
    out += ["## Before each post goes out (the day's checklist)",
            "1. `python3 social/tools/feed.py stats` and update every number; set `measured_on` to the post day.",
            "2. `python3 social/tools/render_posts.py <this week>.posts.json --only <id>` (roles are re-picked from the live feed).",
            "3. `node social/tools/verify-open.js social/output/<date>/<id>/manifest.json` (exit 0 needed: open, title matches, no single-country wording on a wide card).",
            "4. Copy the checked roles into `featured_jobs` with `checked_open_on` = the post day.",
            "5. `python3 social/tools/check_post.py <this week>.posts.json --mode schedule` (exit 0 needed).",
            "6. Look at every slide; schedule in Postiz at least 2 hours ahead (Phase 1: only after KT's yes for the week).", ""]
    md = path.with_name(path.name.replace(".posts.json", ".md"))
    md.write_text("\n".join(out), encoding="utf-8")
    return md


if __name__ == "__main__":
    for a in sys.argv[1:]:
        print(build(Path(a)))
